import fs from "fs";
import path from "path";

const src = "babubi/static_src/icons";
const dest = "babubi/static_src/scss/icons/_generated.scss";

/**
 * Writes the SVG icons as a Sass map of URL-encoded data, for the stylesheet
 * to draw them as CSS masks (babubi/static_src/scss/icons/icons.scss).
 */
export function icons(cb) {
  const entries = fs
    .readdirSync(src)
    .filter((file) => file.endsWith(".svg"))
    .sort()
    .map((file) => {
      const svg = fs
        .readFileSync(path.join(src, file), "utf8")
        .replace(/\s*\n\s*/g, " ")
        .trim()
        .replace(/"/g, "'")
        .replace(/%/g, "%25")
        .replace(/#/g, "%23")
        .replace(/</g, "%3C")
        .replace(/>/g, "%3E");
      return `  "${path.basename(file, ".svg")}": "${svg}",`;
    });
  fs.writeFileSync(
    dest,
    `// Generated by gulpfile.icons.js from ${src}: do not edit.\n` +
      `$icons: (\n${entries.join("\n")}\n);\n`,
  );
  cb();
}

export const iconsGlob = `${src}/*.svg`;
